// Helper to generate realistic historical chart series
function generateChartData(basePrice: number, changePercent: number, count: number = 30) {
  const points = [];
  const startPrice = basePrice / (1 + changePercent / 100);
  const now = new Date();
  
  for (let i = 0; i < count; i++) {
    const progress = i / (count - 1);
    // Smooth interpolation with realistic financial noise
    const trend = startPrice + (basePrice - startPrice) * progress;
    const noise = (Math.sin(i * 1.5) + Math.cos(i * 0.8)) * (basePrice * 0.015);
    const p = Math.max(1, Number((trend + noise).toFixed(2)));
    const date = new Date(now.getTime() - (count - 1 - i) * 24 * 3600 * 1000);
    
    points.push({
      date: date.toLocaleDateString('en-US', { month: 'short', day: 'numeric' }),
      price: i === count - 1 ? basePrice : p,
      volume: Math.floor(Math.random() * 5000000 + 1000000),
    });
  }
  return points;
}

